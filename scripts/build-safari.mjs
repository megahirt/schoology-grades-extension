#!/usr/bin/env node
/**
 * Build the Safari version of the Schoology Dashboard extension.
 *
 *   node scripts/build-safari.mjs [--dev]
 *
 * Safari-first: many students use Safari, so the
 * Safari build is the primary distribution target (Chrome Web Store is
 * second). The shared extension is Safari-compatible from day one
 * (webextension-polyfill, browser.* Promise APIs, bundled pure-JS parser,
 * no sidePanel / offscreen / declarativeNetRequest in the critical path).
 *
 * What this script does:
 *   1. Builds the shared extension for Safari into dist-safari/
 *      (scripts/build.mjs --safari: no optional all-sites permission, see
 *      WebKit bug 290508 in docs/schoology-domains-research.md); falls back
 *      to the extension/ source folder if that script is missing.
 *   2. Converts it to an Xcode project with Apple's packager:
 *        xcrun safari-web-extension-packager   (new name, WWDC26 — try first)
 *        xcrun safari-web-extension-converter  (older Xcode name — fallback)
 *      The packager generates an Xcode project with a native macOS app
 *      wrapper + the extension embedded as a .appex.
 *   3. On a machine without Xcode (e.g. this Linux VM, or Linux CI) the
 *      converter is unavailable — that is EXPECTED, not a failure. The
 *      script then writes safari/convert.sh with the exact command to run
 *      on a Mac, and exits 0.
 *
 * After conversion, manual steps on the Mac (see docs/safari.md):
 *   - Strip browser_specific_settings / key / side_panel / offscreen from
 *     the manifest if present; verify every target's bundle ID in Xcode
 *     (the converter sometimes mangles them — app vs .Extension suffix).
 *   - Set the Team on every target; build the containing app's help /
 *     settings screen (Guideline 4.4: it must not be blank).
 *   - Local test: Safari Settings > Developer > Allow Unsigned Extensions
 *     (resets every Safari quit) > Add Temporary Extension, or the Xcode
 *     loop (open .xcodeproj, Product > Run). Enabling the extension is
 *     NOT the same as granting page access — allow it on schoology.com
 *     separately or the content script never runs.
 *
 * Bundle ID placeholder: com.example.schoology-dashboard — TO BE REPLACED
 * with the publisher's real bundle ID (e.g. com.<familyname>.schoology-dashboard)
 * before any App Store submission. Bundle IDs can never be reused or
 * changed later, so pick carefully. Never invent a Team ID.
 *
 * No-Mac alternative (iOS 26 era): App Store Connect's web Safari Web
 * Extension Packager — upload a ZIP of the extension, Apple packages it.
 * See docs/safari.md.
 */

import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync, chmodSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dev = process.argv.includes('--dev');

// TO BE REPLACED with the publisher's real bundle ID before submission.
// Placeholder only — do not submit to App Store Connect with this ID.
const BUNDLE_ID = 'com.example.schoology-dashboard';
const APP_NAME = 'Schoology Dashboard';
const SAFARI_DIR = path.join(repoRoot, 'safari');

function run(command, args, options = {}) {
  return spawnSync(command, args, { stdio: 'inherit', ...options });
}

function toolAvailable(tool) {
  // `xcrun -find <tool>` exits 0 when the tool exists in the active Xcode.
  const found = spawnSync('xcrun', ['-find', tool], { stdio: 'pipe' });
  return found.status === 0;
}

function convertCommand(tool, inputDir) {
  return (
    `xcrun ${tool} --copy-resources "${inputDir}" \\\n` +
    `  --project-location "${SAFARI_DIR}" \\\n` +
    `  --app-name "${APP_NAME}" \\\n` +
    `  --bundle-identifier ${BUNDLE_ID} \\\n` +
    `  --swift --macos-only --no-open`
  );
}

function writeConvertScript(inputDir) {
  mkdirSync(SAFARI_DIR, { recursive: true });
  // Keep the path relative to the repo root so the generated script is
  // portable (it cds to the repo root before running the packager).
  const relativeInput = path.relative(repoRoot, inputDir) || '.';
  const script = `#!/bin/sh
# Generated by scripts/build-safari.mjs on a machine without Xcode.
# Run this ON A MAC with full Xcode installed (Command Line Tools alone
# is not enough for the Xcode-project step).
#
# Tries the new packager name first (WWDC26), falls back to the older
# converter name on older Xcode. Exact flags are from Apple's WWDC26
# session + consistent secondary sources — verify with
# \`xcrun safari-web-extension-packager --help\` on the build Mac.
#
# BUNDLE ID PLACEHOLDER: com.example.schoology-dashboard
#   TO BE REPLACED with the publisher's real bundle ID before any App Store
#   submission. Bundle IDs can never be reused or changed later.
set -e
cd "$(dirname "$0")/.."
INPUT="${relativeInput}"
if xcrun -find safari-web-extension-packager >/dev/null 2>&1; then
  TOOL=safari-web-extension-packager
elif xcrun -find safari-web-extension-converter >/dev/null 2>&1; then
  TOOL=safari-web-extension-converter
else
  echo "ERROR: neither safari-web-extension-packager nor safari-web-extension-converter was found." >&2
  echo "Install full Xcode from the Mac App Store and try again." >&2
  exit 1
fi
echo "Using $TOOL with input: $INPUT"
xcrun "$TOOL" --copy-resources "$INPUT" \\
  --project-location "./safari" \\
  --app-name "${APP_NAME}" \\
  --bundle-identifier ${BUNDLE_ID} \\
  --swift --macos-only --no-open
echo ""
echo "Done. Next steps (see docs/safari.md):"
echo "  - Open safari/*.xcodeproj, set the Team on EVERY target (app + extension)."
echo "  - Verify each target's bundle ID (converter sometimes mangles the .Extension suffix)."
echo "  - Strip browser_specific_settings / key / side_panel / offscreen from the manifest if present."
echo "  - Build the containing app's help/settings screen (Guideline 4.4 — it must not be blank)."
`;
  const scriptPath = path.join(SAFARI_DIR, 'convert.sh');
  writeFileSync(scriptPath, script, 'utf8');
  chmodSync(scriptPath, 0o755);
  return scriptPath;
}

function ensureSafariReadme() {
  const readmePath = path.join(SAFARI_DIR, 'README.md');
  if (existsSync(readmePath)) {
    return;
  }
  writeFileSync(
    readmePath,
    `# Safari build output\n\nThis directory holds the Xcode project generated by Apple's Safari web\n` +
      `extension packager (see \`convert.sh\`, generated by\n` +
      `\`node scripts/build-safari.mjs\`). It is created on a Mac — on Linux\n` +
      `only \`convert.sh\` exists here.\n\nFull pipeline, local testing, TestFlight, and App Store submission:\n` +
      `see \`docs/safari.md\` in the repo root.\n\nBundle ID placeholder: \`com.example.schoology-dashboard\` —\n` +
      `TO BE REPLACED with the publisher's real bundle ID before submission.\n`,
    'utf8'
  );
}

// --- 1. Make sure the shared extension is built ---------------------------
const distDir = path.join(repoRoot, 'dist-safari');
const buildScript = path.join(repoRoot, 'scripts', 'build.mjs');
let inputDir = distDir;

{
  if (existsSync(buildScript)) {
    console.log('Building the extension for Safari (dist-safari/)…');
    const result = run('node', [buildScript, '--safari', ...(dev ? ['--dev'] : [])]);
    if (result.status !== 0) {
      console.error('ERROR: the main build (scripts/build.mjs) failed.');
      process.exit(result.status ?? 1);
    }
  } else {
    console.log(
      'WARNING: scripts/build.mjs is not present yet ' +
        '(it is built by another workstream). Using extension/ source as the ' +
        'converter input instead — re-run this script once the main build lands.'
    );
    inputDir = path.join(repoRoot, 'extension');
  }
}

// --- 2. Convert (or generate the converter script) ------------------------
mkdirSync(SAFARI_DIR, { recursive: true });

let packager = null;
if (toolAvailable('safari-web-extension-packager')) {
  packager = 'safari-web-extension-packager';
} else if (toolAvailable('safari-web-extension-converter')) {
  console.log('NOTE: safari-web-extension-packager not found; falling back to the older safari-web-extension-converter name.');
  packager = 'safari-web-extension-converter';
}

if (packager) {
  console.log(`Running ${packager} …`);
  const args = [
    packager,
    '--copy-resources',
    inputDir,
    '--project-location',
    SAFARI_DIR,
    '--app-name',
    APP_NAME,
    '--bundle-identifier',
    BUNDLE_ID,
    '--swift',
    '--macos-only',
    '--no-open'
  ];
  const result = run('xcrun', args);
  if (result.status !== 0) {
    console.error(`ERROR: ${packager} failed (exit ${result.status}).`);
    console.error('Check the converter output above; verify bundle IDs and manifest keys, then re-run.');
    process.exit(result.status ?? 1);
  }
  console.log(`\nSafari Xcode project generated in ${SAFARI_DIR}`);
  console.log('Next: open the .xcodeproj, set the Team on every target, verify bundle IDs — see docs/safari.md.');
} else {
  const scriptPath = writeConvertScript(inputDir);
  console.log(
    '\nNOTE: xcrun safari-web-extension-packager/converter is unavailable on this machine ' +
      '(macOS + full Xcode required). This is expected on Linux / Linux CI — not a failure.'
  );
  console.log(`Generated converter command script: ${scriptPath}`);
  console.log('Run it on a Mac with Xcode installed to produce the Xcode project in safari/.');
  console.log('No-Mac alternative: App Store Connect web Safari Web Extension Packager (upload a ZIP) — see docs/safari.md.');
}

ensureSafariReadme();
console.log(`\nSafari build step done. Input: ${inputDir}`);
console.log(`Bundle ID (PLACEHOLDER — TO BE REPLACED before submission): ${BUNDLE_ID}`);
